def normalize_school(text):
    """比對用：統一「台／臺」、去掉空白，例如「國立台灣 大學」→「國立臺灣大學」。"""
    return "".join((text or "").split()).replace("台", "臺")


def canonical_school(text):
    """輸入的是清單上的學校（或它的簡稱、台／臺寫法不同）就換成正式名稱；否則照原樣保留。"""
    text = (text or "").strip()
    key = normalize_school(text)
    for name in flat(SCHOOLS):
        if key == normalize_school(name) or key in {normalize_school(a) for a in SCHOOL_ALIASES.get(name, [])}:
            return name
    return text


